#!/usr/bin/env python3
"""
YOLOv8 裂缝/落石检测模型训练脚本。

使用 Ultralytics YOLOv8 在裂缝数据集上微调，导出 ONNX。
训练完成后将模型放入 ai-service/models/yolo_crack.onnx 即可启用真实推理。

数据集格式（YOLO 标准）:
    data_root/
    ├── images/train/*.jpg
    ├── images/val/*.jpg
    ├── labels/train/*.txt   # 每行: class_id cx cy w h (归一化)
    └── labels/val/*.txt

类别: crack, rockfall, slump, debris, normal

用法:
    python train_crack_yolo.py --data ./datasets/crack --epochs 50 --imgsz 640
    python train_crack_yolo.py --data ./datasets/crack --export-onnx
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path


CLASSES = ["crack", "rockfall", "slump", "debris", "normal"]


def build_yaml(data_root: Path, out_yaml: Path) -> Path:
    """生成 YOLO dataset YAML。"""
    data_root = data_root.resolve()
    yaml = f"""# Auto-generated by train_crack_yolo.py
path: {data_root}
train: images/train
val: images/val
names:
"""
    for i, cls in enumerate(CLASSES):
        yaml += f"  {i}: {cls}\n"
    out_yaml.write_text(yaml)
    print(f"[train] 生成 dataset YAML: {out_yaml}")
    return out_yaml


def train(data_yaml: Path, epochs: int, imgsz: int, project: str, name: str):
    try:
        from ultralytics import YOLO
    except ImportError:
        print("[ERROR] 请先安装 ultralytics: pip install ultralytics")
        sys.exit(1)

    model = YOLO("yolov8n.pt")  # nano 预训练权重，适合边缘设备
    results = model.train(
        data=str(data_yaml),
        epochs=epochs,
        imgsz=imgsz,
        batch=16,
        project=project,
        name=name,
        exist_ok=True,
        augment=True,
    )
    best_pt = Path(project) / name / "weights" / "best.pt"
    print(f"[train] 训练完成，最佳权重: {best_pt}")
    return best_pt


def export_onnx(pt_path: Path, imgsz: int, output_path: Path):
    try:
        from ultralytics import YOLO
    except ImportError:
        print("[ERROR] 请先安装 ultralytics")
        sys.exit(1)

    model = YOLO(str(pt_path))
    model.export(format="onnx", imgsz=imgsz, simplify=True, opset=17)
    onnx_path = pt_path.with_suffix(".onnx")
    if onnx_path.exists() and not output_path.exists():
        output_path.parent.mkdir(parents=True, exist_ok=True)
        onnx_path.rename(output_path)
    print(f"[train] ONNX 导出完成: {output_path}")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", required=True, help="数据集根目录（含 images/train, labels/train 等）")
    parser.add_argument("--epochs", type=int, default=50)
    parser.add_argument("--imgsz", type=int, default=640)
    parser.add_argument("--project", default="runs/crack")
    parser.add_argument("--name", default="yolov8n")
    parser.add_argument("--export-onnx", action="store_true", help="训练完成后导出 ONNX")
    parser.add_argument("--models-dir", default=str(Path(__file__).resolve().parent.parent.parent / "models"))
    args = parser.parse_args()

    data_root = Path(args.data)
    if not data_root.exists():
        print(f"[ERROR] 数据集目录不存在: {data_root}")
        sys.exit(1)

    yaml_path = build_yaml(data_root, data_root / "dataset.yaml")
    best_pt = train(yaml_path, args.epochs, args.imgsz, args.project, args.name)

    if args.export_onnx:
        models_dir = Path(args.models_dir)
        models_dir.mkdir(parents=True, exist_ok=True)
        export_onnx(best_pt, args.imgsz, models_dir / "yolo_crack.onnx")


if __name__ == "__main__":
    main()
