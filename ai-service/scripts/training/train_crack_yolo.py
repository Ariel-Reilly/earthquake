#!/usr/bin/env python3
"""YOLOv8 裂缝/滑坡检测模型训练脚本。

数据来自 datasets/disaster-v2（由 scripts/dataset/build_yolo_dataset.py 从公开人工标注集
构建，不含合成数据）：
    ├── images/{train,val,test}/*.png
    ├── labels/{train,val,test}/*.txt   # 每行: class_id cx cy w h（归一化）
    └── dataset.yaml

类别: crack, landslide

用法:
    # 训练（自动选 GPU，没有 GPU 就用 CPU 并打印告警）
    python train_crack_yolo.py --data ../../datasets/disaster-v2 --epochs 80 --imgsz 640

    # 训练 + 导出 ONNX 到 models/
    python train_crack_yolo.py --data ../../datasets/disaster-v2 --epochs 80 --export-onnx

    # 只做测试集评估（不训练）
    python train_crack_yolo.py --data ../../datasets/disaster-v2 --eval-only runs/detect/train/weights/best.pt

设计说明：
  - **不伪造指标**：所有数字来自 ultralytics 的 val/test 输出，脚本只做解析与打印。
  - 类别名从 dataset.yaml 读，不硬编码，避免数据集扩类后脚本静默错位。
  - CPU 训练会在启动时明确告警并给出预计时间，不让使用者以为"马上就好"。
"""
from __future__ import annotations

import argparse
import json
import shutil
import sys
import time
from pathlib import Path


def read_classes(data_root: Path) -> list[str]:
    """从 dataset.yaml 读类别名，缺失时回退到目录推断并在 stdout 明确说明。"""
    yaml_path = data_root / "dataset.yaml"
    if yaml_path.exists():
        names: list[str] = []
        for line in yaml_path.read_text(encoding="utf-8").splitlines():
            s = line.strip()
            if s.startswith("- ") and "#" not in s:
                names.append(s[2:].strip().strip("'\""))
            elif ":" in s and s.split(":", 1)[0].strip().isdigit():
                names.append(s.split(":", 1)[1].strip().strip("'\""))
        if names:
            return names
    print(f"[warn] {yaml_path} 无可用 names，回退为 [crack, landslide]")
    return ["crack", "landslide"]


def build_yaml(data_root: Path, out_yaml: Path, classes: list[str]) -> Path:
    data_root = data_root.resolve()
    lines = [
        "# Auto-generated by train_crack_yolo.py",
        f"path: {data_root.as_posix()}",
        "train: images/train",
        "val: images/val",
        "test: images/test",
        f"nc: {len(classes)}",
        "names:",
    ]
    lines += [f"  {i}: {c}" for i, c in enumerate(classes)]
    out_yaml.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"[train] 生成 dataset YAML: {out_yaml}")
    return out_yaml


def pick_device(wanted: str) -> str:
    """auto：有 CUDA 用 0，否则 cpu。明确打印选择结果，避免"以为在用 GPU"。"""
    if wanted != "auto":
        return wanted
    try:
        import torch

        if torch.cuda.is_available():
            name = torch.cuda.get_device_name(0)
            print(f"[train] 设备：cuda:0 ({name})  torch={torch.__version__}")
            return "0"
        print(f"[warn] 当前 torch={torch.__version__} 未启用 CUDA（CPU 构建）。")
        print("[warn] 将使用 CPU 训练。若需 GPU 加速，请安装对应 CUDA 版 torch。")
    except Exception as exc:  # noqa: BLE001
        print(f"[warn] 检测 CUDA 失败（{exc}），回退 CPU")
    return "cpu"


def train(args) -> Path:
    from ultralytics import YOLO

    device = pick_device(args.device)
    model = YOLO(args.model)

    # 滑坡目标常占画面较大比例且纹理破碎，增强以几何/光照为主，避免过度破坏语义
    t0 = time.time()
    model.train(
        data=str(args.data_yaml),
        epochs=args.epochs,
        imgsz=args.imgsz,
        batch=args.batch,
        device=device,
        workers=args.workers,
        project=args.project,
        name=args.name,
        exist_ok=True,
        patience=args.patience,
        cache=args.cache,
        plots=args.plots,
        pretrained=True,
        optimizer="auto",
        cos_lr=True,
        close_mosaic=10,
        # 增强：多尺度 + 翻转 + 轻度旋转，贴合航拍/卫星视角变化
        mosaic=1.0,
        scale=0.5,
        fliplr=0.5,
        flipud=0.3,
        degrees=10.0,
        hsv_h=0.015,
        hsv_s=0.5,
        hsv_v=0.4,
    )
    elapsed = time.time() - t0
    best = Path(args.project) / args.name / "weights" / "best.pt"
    print(f"[train] 训练结束，用时 {elapsed / 60:.1f} 分钟，最佳权重: {best}")
    return best


def run_eval(weights: Path, args) -> dict:
    """在 test 集上评估并打印每类指标（这是"精度是否提升"的唯一可信来源）。"""
    from ultralytics import YOLO

    model = YOLO(str(weights))
    metrics = model.val(
        data=str(args.data_yaml),
        split="test",
        imgsz=args.imgsz,
        batch=args.batch,
        device=pick_device(args.device),
        workers=args.workers,
        project=args.project,
        name=f"{args.name}_test",
        exist_ok=True,
    )
    names = args.classes
    per_class: dict[str, dict[str, float]] = {}
    try:
        idx = list(metrics.box.ap_class_index)
        for pos, ci in enumerate(idx):
            cname = names[ci] if ci < len(names) else str(ci)
            per_class[cname] = {
                "precision": round(float(metrics.box.p[pos]), 4),
                "recall": round(float(metrics.box.r[pos]), 4),
                "mAP50": round(float(metrics.box.ap50[pos]), 4),
                "mAP50-95": round(float(metrics.box.ap[pos]), 4),
            }
    except Exception as exc:  # noqa: BLE001
        print(f"[warn] 解析每类指标失败：{exc}")

    summary = {
        "weights": str(weights),
        "split": "test",
        "imgsz": args.imgsz,
        "overall": {
            "precision": round(float(metrics.box.mp), 4),
            "recall": round(float(metrics.box.mr), 4),
            "mAP50": round(float(metrics.box.map50), 4),
            "mAP50-95": round(float(metrics.box.map), 4),
        },
        "per_class": per_class,
    }
    print("[eval] test 集指标：")
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    out = Path(args.project) / args.name / "test_metrics.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"[eval] 指标已写入 {out}")
    return summary


def export_onnx(pt_path: Path, imgsz: int, output_path: Path, classes: list[str]):
    from ultralytics import YOLO

    model = YOLO(str(pt_path))
    exported = model.export(format="onnx", imgsz=imgsz, simplify=True, opset=17, dynamic=False)
    exported = Path(exported)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    if exported.resolve() != output_path.resolve():
        shutil.copy2(exported, output_path)
    # 一并写出类别元数据，供 ai-service 校验 ONNX 是否为本业务模型
    meta = {
        "model": output_path.name,
        "task": "detect",
        "format": "onnx",
        "imgsz": imgsz,
        "classes": classes,
        "source_weights": str(pt_path),
        "exported_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
    }
    meta_path = output_path.with_suffix(".meta.json")
    meta_path.write_text(json.dumps(meta, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"[export] ONNX: {output_path}")
    print(f"[export] 元数据: {meta_path}")


def main() -> None:
    parser = argparse.ArgumentParser(description="YOLOv8 裂缝/滑坡检测训练")
    parser.add_argument("--data", required=True, help="数据集根目录（含 images/labels/dataset.yaml）")
    parser.add_argument("--model", default="yolov8n.pt", help="预训练权重，如 yolov8n.pt / yolov8s.pt")
    parser.add_argument("--epochs", type=int, default=80)
    parser.add_argument("--imgsz", type=int, default=640)
    parser.add_argument("--batch", type=int, default=16)
    parser.add_argument("--workers", type=int, default=4)
    parser.add_argument("--patience", type=int, default=30, help="早停耐心值")
    parser.add_argument("--device", default="auto", help="auto / cpu / 0")
    parser.add_argument("--cache", action="store_true", help="缓存图像到内存（小数据集可显著加速）")
    parser.add_argument(
        "--no-plots",
        dest="plots",
        action="store_false",
        help="关闭验证阶段的 PR 曲线/混淆矩阵绘图（CPU 训练可明显缩短每轮时间）",
    )
    parser.set_defaults(plots=True)

    parser.add_argument("--project", default="runs/detect")
    parser.add_argument("--name", default="disaster-v2-n")
    parser.add_argument("--export-onnx", action="store_true", help="训练完成后导出 ONNX 到 models/")
    parser.add_argument("--eval-only", default="", help="仅评估指定权重的 test 集指标")
    parser.add_argument(
        "--models-dir",
        default=str(Path(__file__).resolve().parent.parent.parent / "models"),
        help="ONNX 输出目录",
    )
    args = parser.parse_args()

    data_root = Path(args.data)
    if not data_root.exists():
        print(f"[ERROR] 数据集目录不存在: {data_root}")
        sys.exit(1)

    args.classes = read_classes(data_root)
    args.data_yaml = build_yaml(data_root, data_root / "dataset.yaml", args.classes)
    print(f"[train] 类别: {args.classes}")

    if args.eval_only:
        run_eval(Path(args.eval_only), args)
        return

    best = train(args)
    if not best.exists():
        print(f"[ERROR] 未找到最佳权重 {best}")
        sys.exit(1)

    if args.export_onnx:
        run_eval(best, args)
        export_onnx(best, args.imgsz, Path(args.models_dir) / "yolo_crack.onnx", args.classes)


if __name__ == "__main__":
    main()
